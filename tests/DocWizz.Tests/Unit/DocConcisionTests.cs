namespace DocWizz.Tests.Unit;

public class DocConcisionTests
{
    static CheckConfig Limits() => new() { MaxDocumentWords = 20, MaxParagraphWords = 5 };

    [Fact]
    public void Wrapped_wall_is_one_paragraph()
    {
        var finding = Assert.Single(DocConcision.Inspect("# Title\n\none two three\nfour five six", Limits()));
        Assert.Equal("DOC-002", finding.Rule);
        Assert.Equal(3, finding.Line);
        Assert.Contains("remove repetition", finding.Advice);
    }

    [Fact]
    public void Short_paragraphs_do_not_hide_document_bloat()
    {
        var text = string.Join("\n\n", Enumerable.Repeat("one two three four five", 5));
        Assert.Equal("DOC-001", Assert.Single(DocConcision.Inspect(text, Limits())).Rule);
    }

    [Fact]
    public void Code_and_generated_pages_are_ignored()
    {
        Assert.Empty(DocConcision.Inspect("~~~cs\n" + new string('x', 1000) + "\n~~~\nShort prose.", Limits()));
        Assert.Empty(DocConcision.Inspect("<!-- generated by docwizz: edits are overwritten -->\n" +
            string.Join(" ", Enumerable.Repeat("word", 100)), Limits()));
    }

    [Fact]
    public void Existing_debt_must_not_increase()
    {
        var old = DocConcision.Inspect("one two three four five six", Limits());
        var larger = DocConcision.Inspect("one two three four five six seven", Limits());
        Assert.Empty(DocConcision.Regressions(old, old));
        Assert.Empty(DocConcision.Regressions(old, larger));
        Assert.Single(DocConcision.Regressions(larger, old));
    }
}
