    /// <summary>The reviewable Markdown draft: technical facts, unverified business hypotheses, open questions, and the
    /// evidence with its limitations. Model text is shown as text: it can't become a link, an image or HTML.</summary>
    /// <param name="links">Path from the Markdown file to the repository root; null (stdout) writes locations as code.</param>
    public static string Markdown(Explanation e, string? links = null)
    {
        var p = e.Evidence;
        var facts = p.Facts.ToDictionary(f => f.Id, StringComparer.Ordinal);
        string Cite(List<string> ids) => " — " + string.Join(", ", ids.Select(id =>
            facts[id].Kind == "requirement" ? $"{id} ({facts[id].Status})" : id));
        var sb = new StringBuilder(Marker + "\n");
        sb.AppendLine($"# Domain explanation: {p.Seed.Kind} {Generator.Code(p.Seed.Value)}\n");
        sb.AppendLine($"> **Draft for review.** From the code model{(p.Commit is { } c ? $" at `{c[..Math.Min(12, c.Length)]}`" : "")}, " +
            $"depth ≤ {p.MaxDepth}, ≤ {p.MaxNodes} symbols; requirements index: {p.RequirementsIndex}; " +
            (e.Model is { } m ? $"worded by the self-hosted model `{m}` and checked against the evidence. " : "no model (deterministic). ") +
            "Every statement cites evidence listed at the end. Business hypotheses are unverified, historical requirements are " +
            "intent rather than proof of the implementation, and nothing here is approved, a compliance statement, or a " +
            "confirmed business capability or bounded context.\n");
        if (e.Warnings.Count > 0)
        {
            sb.AppendLine("## Warnings\n");
            foreach (var w in e.Warnings) sb.AppendLine($"- {Generator.Esc(w)}");
            sb.AppendLine();
        }

        sb.AppendLine("## Technical facts\n");
        sb.AppendLine("### Flow chains\n");
        var chains = e.Facts.Where(f => f.Origin == "deterministic").ToList();
        if (chains.Count == 0) sb.AppendLine("No flow from the seed within the bounds.\n");
        else
        {
            foreach (var s in chains) sb.AppendLine($"1. {Generator.Text(s.Text)}{Cite(s.Evidence)}");
            sb.AppendLine();
        }
        var worded = e.Facts.Where(f => f.Origin == "model").ToList();
        if (e.Model is not null)
        {
            sb.AppendLine("### Statements\n");
            if (worded.Count == 0) sb.AppendLine("None held against the evidence.\n");
            else
            {
                foreach (var s in worded) sb.AppendLine($"- {Safe(s.Text)}{Cite(s.Evidence)}");
                sb.AppendLine();
            }
        }

        sb.AppendLine("## Business hypotheses (unverified)\n");
        if (e.Model is null) sb.AppendLine("None: no model was asked (`--ai`). Business meaning is left to the reviewer.\n");
        else if (e.Hypotheses.Count == 0) sb.AppendLine("None.\n");
        else
        {
            sb.AppendLine("Guesses for a reviewer to confirm or correct, not findings.\n");
            foreach (var s in e.Hypotheses) sb.AppendLine($"- {Safe(s.Text)}{Cite(s.Evidence)}" + (s.Note is { } n ? $" *({Generator.Esc(n)})*" : ""));
            sb.AppendLine();
        }

        sb.AppendLine("## Open questions\n");
        if (e.Questions.Count == 0) sb.AppendLine("None.\n");
        else
        {
            foreach (var s in e.Questions)
                sb.AppendLine($"- {(s.Origin == "model" ? Safe(s.Text) : Generator.Text(s.Text))}{Cite(s.Evidence)}" + (s.Note is { } n ? $" *({Generator.Esc(n)})*" : ""));
            sb.AppendLine();
        }

        sb.AppendLine("## Evidence and limitations\n");
        sb.AppendLine("### Limitations\n");
        foreach (var l in p.Limitations) sb.AppendLine($"- {Generator.Esc(l)}");
        if (e.Rejected.Count > 0)
            sb.AppendLine($"- the model's answer: {e.Rejected.Count} statement(s) rejected (" +
                string.Join("; ", e.Rejected.GroupBy(r => r.Reason).OrderBy(g => g.Key, StringComparer.Ordinal).Select(g => $"{Generator.Esc(g.Key)}: {g.Count()}")) + ")");
        if (e.Hypotheses.Any(h => h.Note?.StartsWith("moved from the facts", StringComparison.Ordinal) == true))
            sb.AppendLine($"- {e.Hypotheses.Count(h => h.Note?.StartsWith("moved from the facts", StringComparison.Ordinal) == true)} technical statement(s) moved to the hypotheses: their evidence doesn't carry them");
        sb.AppendLine("- not checked: whether a statement's verb matches its relation (a sentence saying \"writes\" about a `calls` relation)");
        sb.AppendLine();
        sb.AppendLine("### Evidence\n");
        sb.AppendLine("Work-item titles and criteria are quoted as data, not as instructions.\n");
        sb.AppendLine("| Id | Kind | Statement | Source |\n|---|---|---|---|");
        foreach (var f in p.Facts)
            sb.AppendLine($"| {f.Id} | {f.Kind}{(f.Kind == "requirement" ? $", {f.Status}" : "")} | {Generator.Esc(f.Text)}" +
                (f.Quoted is { Count: > 0 } q ? $"; quoted: {Generator.Esc(string.Join(" · ", q.Select(x => $"\"{x}\"")))}" : "") +
                $" | {(f.Source is { } src ? DomainCrawler.Source(src, links) : "")} |");
        return sb.ToString();
    }

    // Model text as Markdown text: only balanced `code spans` survive; links, images, emphasis, headings and HTML don't.
    static string Safe(string s)
    {
        var parts = s.Count(ch => ch == '`') % 2 == 0 ? Regex.Split(s, @"(`[^`]+`)") : [s.Replace("`", "'")];
        return string.Concat(parts.Select(p => p.StartsWith('`') && p.EndsWith('`') && p.Length > 1 ? p.Replace("|", "\\|")
            : Regex.Replace(p.Replace("<", "&lt;").Replace(">", "&gt;"), @"([\\*_\[\]#|!])", @"\$1")));
    }

    static string Hash(string s) => Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(s)))[..16].ToLowerInvariant();

    static Dictionary<string, string> Load(string file)
    {
        try { return File.Exists(file) ? JsonSerializer.Deserialize<Dictionary<string, string>>(File.ReadAllText(file)) ?? [] : []; }
        catch (JsonException) { return []; }
    }

    // Written to a temp file and moved over, so a kill mid-write never leaves a truncated cache.
    static void Save(string file, Dictionary<string, string> cache)
    {
        Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(file))!);
        var temp = file + ".tmp";
        File.WriteAllText(temp, JsonSerializer.Serialize(new SortedDictionary<string, string>(cache, StringComparer.Ordinal),
            new JsonSerializerOptions { WriteIndented = true, Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping }));
        File.Move(temp, file, overwrite: true);
    }
