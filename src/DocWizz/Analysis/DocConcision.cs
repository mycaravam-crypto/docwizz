using System.Text.RegularExpressions;

// Deterministic readability signals, not a semantic assessment of documentation correctness.
static class DocConcision
{
    public record Finding(string Rule, int Line, int Actual, int Limit, string Advice)
    {
        public string Message(string path) => $"{Rule} {path}:{Line}: {Actual} words (limit {Limit}). {Advice}";
    }

    static int Words(string text) => Regex.Matches(text, @"[\p{L}\p{N}]+(?:['’-][\p{L}\p{N}]+)*").Count;

    public static List<Finding> Inspect(string text, CheckConfig config)
    {
        var lines = text.Replace("\r\n", "\n").Split('\n');
        if (lines.Take(2).Any(l => l.Contains("<!-- generated by docwizz: edits are overwritten -->"))) return [];
        var findings = new List<Finding>();
        int total = 0, paragraph = 0, start = 1;
        char fence = '\0';
        int fenceLength = 0;
        void Flush()
        {
            if (paragraph > config.MaxParagraphWords)
                findings.Add(new("DOC-002", start, paragraph, config.MaxParagraphWords,
                    "Keep the key point; remove repetition and split distinct ideas into short paragraphs."));
            paragraph = 0;
        }
        for (int i = 0; i < lines.Length; i++)
        {
            var line = lines[i].Trim();
            var marker = Regex.Match(line, @"^(`{3,}|~{3,})");
            if (marker.Success)
            {
                var value = marker.Value;
                if (fence == '\0') { Flush(); fence = value[0]; fenceLength = value.Length; }
                else if (value[0] == fence && value.Length >= fenceLength && line[value.Length..].Trim().Length == 0)
                    fence = '\0';
                continue;
            }
            if (fence != '\0') continue;
            if (line.Length == 0) { Flush(); continue; }
            if (line.StartsWith('|') || line.StartsWith("<!--")) { Flush(); continue; }
            var words = Words(line);
            total += words;
            if (line.StartsWith('#')) { Flush(); continue; }
            if (Regex.IsMatch(line, @"^(?:[-+*]|\d+[.)])\s+")) Flush();
            if (paragraph == 0) start = i + 1;
            paragraph += words;
        }
        Flush();
        if (total > config.MaxDocumentWords)
            findings.Insert(0, new("DOC-001", 1, total, config.MaxDocumentWords,
                "Rewrite around the reader's task; merge overlapping sections and remove obsolete or redundant detail."));
        return findings;
    }

    // Existing debt is grandfathered only when the same rule's aggregate excess does not increase.
    public static List<Finding> Regressions(List<Finding> current, List<Finding> baseline) =>
        current.GroupBy(f => f.Rule).Where(g =>
            g.Sum(f => f.Actual - f.Limit) > baseline.Where(f => f.Rule == g.Key).Sum(f => f.Actual - f.Limit))
            .SelectMany(g => g).ToList();
}
