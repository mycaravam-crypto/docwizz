using System.Text;
using System.Text.RegularExpressions;
using System.Xml.Linq;

// Writes the docs/ tree. Everything here is derived from the model; nothing is hand-maintained.
partial class Generator(string root, string outDir, CodeModel model, List<DocumentationItem> findings, ArchitectureResult arch, Config config,
    Dictionary<string, string> drafts, Dictionary<string, AiProse.Draft>? overviews = null,
    Dictionary<string, AiProse.Assessment>? assessments = null)
{
    public const string Marker = "<!-- generated by docwizz: edits are overwritten -->";

    // Also write an HTML twin of every page (Html.cs).
    public bool WriteHtml { get; init; }
    public bool RebuildHtml { get; init; }
    public Action<int, int>? OnPageProcessed { get; init; }
    // Repository files (relative, `/`-separated) after exclude:/.gitignore; the deployment view picks its descriptors from them.
    public List<string> Files { get; init; } = [];
    static readonly string[] TopKinds = ["class", "record", "struct", "interface", "type", "enum", "delegate", "component", "module", "store",
        "procedure", "sql-function", "sql-view", "trigger", "table", "migration"];
    const int MaxDiagramEdges = 60;

    readonly ArchitectureConfig archConfig = config.Architecture;
    // Layer and custom rule violations, and security findings (SEC-*, only with security.enabled), shown apart.
    List<Violation> LayerViolations => arch.Violations.Where(v => v.Concern is null).ToList();
    List<Violation> SecurityFindings => arch.Violations.Where(v => v.Concern is not null).ToList();
    readonly Dictionary<string, Node> nodes = model.Nodes.ToDictionary(n => n.Id);
    readonly Dictionary<string, string> parent = model.Edges.Where(e => e.Kind == "contains").ToDictionary(e => e.To, e => e.From);
    readonly ILookup<string, string> children = model.Edges.Where(e => e.Kind == "contains").ToLookup(e => e.From, e => e.To);
    readonly ILookup<string, string> implOf = model.Edges.Where(e => e.Kind == "implements").ToLookup(e => e.From, e => e.To);
    readonly Dictionary<string, DocumentationItem> findingOf = findings.ToDictionary(f => f.Node.Id);
    readonly TestLinks testLinks = new(model);

    // Renders every page, then writes only those whose content changed and removes generated pages that are gone:
    // unchanged pages keep their file (and timestamp), so regenerating after a small change touches only what it affects.
    public (List<string> Pages, List<string> Changed) Run()
    {
        Directory.CreateDirectory(Path.Combine(outDir, "modules"));
        Directory.CreateDirectory(Path.Combine(outDir, "views"));
        var pages = new Dictionary<string, string>();
        void Write(string rel, string body) => pages[rel] = $"{Marker}\n{body}";

        var modules = model.Nodes.Where(n => n.Kind is not ("route" or "project" or "package" or "external" or "config") || parent.ContainsKey(n.Id))
            .GroupBy(n => Folder(n.File)).OrderBy(g => g.Key).ToList();
        foreach (var m in modules) Write($"modules/{Slug(m.Key)}.md", Module(m.Key, m.ToList()));
        Write("index.md", Index(modules.Select(m => m.Key).ToList()));
        Write("architecture.md", ArchitecturePage(modules.Select(m => m.Key).ToList()));
        Write("api.md", Api());
        Write("frontend.md", FrontendPage());
        Write("quality.md", Quality());
        foreach (var (page, _, body) in Views()) Write($"views/{page}.md", body());
        Write("architecture-description.md", DescriptionPage());
        pages["search.json"] = SearchIndex();
        if (WriteHtml)
        {
            var markdown = pages.Where(p => p.Key.EndsWith(".md")).ToDictionary(p => p.Key, p => Html.Title(p.Key, p.Value));
            foreach (var rel in markdown.Keys) pages[Path.ChangeExtension(rel, ".html")] = Html.Page(rel, pages[rel], markdown);
            pages["search.js"] = $"window.docwizzSearch = {pages["search.json"]};\n";
        }

        // Only pages we generated earlier are removed, so renamed/deleted modules don't linger and hand-written ones stay.
        foreach (var f in Directory.EnumerateFiles(outDir, "*.*", SearchOption.AllDirectories).Where(f => f.EndsWith(".md") || f.EndsWith(".html")))
            if (!pages.ContainsKey(Path.GetRelativePath(outDir, f).Replace('\\', '/')) && File.ReadLines(f).Take(2).Contains(Marker)) File.Delete(f);
        var changed = new List<string>();
        var processed = 0;
        foreach (var (rel, content) in pages)
        {
            var file = Path.Combine(outDir, rel);
            // A version refresh rewrites HTML even when it is identical, but only a page whose content differs is "changed".
            var same = File.Exists(file) && File.ReadAllText(file) == content;
            if (!same || (RebuildHtml && rel.EndsWith(".html", StringComparison.OrdinalIgnoreCase))) File.WriteAllText(file, content);
            if (!same) changed.Add(rel);
            OnPageProcessed?.Invoke(++processed, pages.Count);
        }
        return ([.. pages.Keys], changed);
    }

    // Everything a reader might look up, with the page (and anchor) that documents it: for search boxes and tooling.
    string SearchIndex()
    {
        var entries = new List<SearchEntry>();
        void Entry(string name, string kind, string page, string? summary) => entries.Add(new(name, kind, page, summary));
        foreach (var n in model.Nodes.Where(n => TopKinds.Contains(n.Kind) && n.Kind != "module" && Top(n.Id) == n.Id))
            Entry(n.Name, n.Kind, $"modules/{Slug(Folder(n.File))}.md#{Anchor(n.Id)}", WrittenSummary(n));
        foreach (var n in model.Nodes.Where(n => n.Tags?.Contains("endpoint") == true))
            Entry(EndpointLabel(n), "endpoint", "api.md", WrittenSummary(n));
        foreach (var n in model.Nodes.Where(n => n.Kind == "route")) Entry(n.Route ?? n.Name, "route", "frontend.md", null);
        foreach (var n in model.Nodes.Where(n => n.Kind == "config")) Entry(n.Name, "config", "views/deployment.md#configuration", null);
        foreach (var f in model.Nodes.Where(n => n.Kind is not ("route" or "project" or "package" or "external" or "config")).Select(n => Folder(n.File)).Distinct())
            Entry(f, "module", $"modules/{Slug(f)}.md", null);
        return System.Text.Json.JsonSerializer.Serialize(entries.OrderBy(e => e.Name, StringComparer.OrdinalIgnoreCase).ThenBy(e => e.Kind),
            new System.Text.Json.JsonSerializerOptions(System.Text.Json.JsonSerializerDefaults.Web)
            { WriteIndented = true, Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping });
    }

    record SearchEntry(string Name, string Kind, string Page, string? Summary);

    string Index(List<string> modules)
    {
        var sb = new StringBuilder();
        var kinds = model.Nodes.GroupBy(n => n.Kind).ToDictionary(g => g.Key, g => g.Count());
        sb.AppendLine($"# {Path.GetFileName(Path.GetFullPath(root))}\n");
        sb.AppendLine($"Generated from commit `{model.Commit ?? "unknown"}`.\n");
        sb.AppendLine("| | |\n|---|---|");
        foreach (var (label, kind) in new[] { ("Classes & records", "class"), ("Methods", "method"), ("Frontend functions", "function") })
        {
            var n = kind == "class" ? kinds.GetValueOrDefault("class") + kinds.GetValueOrDefault("record") : kinds.GetValueOrDefault(kind);
            if (n > 0) sb.AppendLine($"| {label} | {n} |");
        }
        sb.AppendLine($"| Documentation coverage (profile `{config.Profile}`) | {Analyzer.Coverage(findings):0}% |");
        sb.AppendLine($"| Doc quality (written docs without quality flags) | {Analyzer.Quality(findings):0}% |");
        sb.AppendLine($"| Critical documentation gaps | {findings.Count(Analyzer.IsCritical)} |");
        sb.AppendLine($"| Architecture violations / cycles | {LayerViolations.Count} / {arch.Cycles.Count} |");
        if (config.Security.Enabled) sb.AppendLine($"| Security findings ([review](architecture-description.md#security)) | {SecurityFindings.Count} |");
        sb.AppendLine();
        if (drafts.Count > 0)
            sb.AppendLine($"🤖 marks {drafts.Count} AI-drafted summaries for code that has no docs yet — review them, then move them into the code.\n");
        sb.AppendLine("- [Architecture description](architecture-description.md)\n- [Architecture](architecture.md)\n- [API endpoints](api.md)\n" +
            "- [Frontend](frontend.md)\n- [Quality](quality.md)\n");
        if (Technology().ToList() is { Count: > 0 } tech)
            sb.AppendLine("## Technology\n\n" + string.Join("\n", tech.Select(t => $"- {t}")) + "\n");
        var blocks = Roles.Select(r => (r.Label, Count: model.Nodes.Count(n => n.Kind == r.Match || n.Tags?.Contains(r.Match) == true)))
            .Where(r => r.Count > 0).ToList();
        if (blocks.Count > 0)
            sb.AppendLine("## Building blocks\n\n| Role | Count |\n|---|---|\n" + string.Join("\n", blocks.Select(b => $"| {b.Label} | {b.Count} |")) + "\n");
        sb.AppendLine("## Modules\n");
        foreach (var m in modules) sb.AppendLine($"- [{m}](modules/{Slug(m)}.md) — {Layer(m) ?? "no layer"}");
        return sb.ToString();
    }

