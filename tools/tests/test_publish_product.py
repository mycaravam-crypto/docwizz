import unittest, tempfile, pathlib, hashlib, json, hmac, os, sys
from unittest.mock import patch
sys.path.insert(0,str(pathlib.Path(__file__).resolve().parents[1]))
import publish_product as p
class GateTests(unittest.TestCase):
 def setUp(self):
  self.t=tempfile.TemporaryDirectory();self.addCleanup(self.t.cleanup);root=pathlib.Path(self.t.name)
  self.source=root/"product.md";self.source.write_text("<!-- generated by docwizz product -->\n# Title\n## Deckblatt\n## Dokumentenlenkung\n## Inhaltsverzeichnis\n")
  self.control=root/"control.yaml";self.control.write_text("schema: 1\n")
  self.evidence=root/"product.evidence.json";self.evidence.write_text(json.dumps({"product":"sw-architecture","document_control":{"document_id":"SWA-001","sha256":p.sha(self.control)},"required":{"total":1,"evidenced":1,"open":[]}}))
  self.approval=root/"approval.json"
  self.args=type("Args",(),{"source":self.source,"control":self.control,"evidence":self.evidence,"mode":"release","attestation":self.approval,"check_passed":True})
  self.key="a"*40
 def sign(self,**overrides):
  payload=dict(schema=1,document_id="SWA-001",source_sha256=p.sha(self.source),control_sha256=p.sha(self.control),evidence_sha256=p.sha(self.evidence),reviewer="alice",approver="bob")
  payload.update(overrides)
  self.approval.write_text(json.dumps({"payload":payload,"signature":hmac.new(self.key.encode(),p.canon(payload),hashlib.sha256).hexdigest()}))
 def test_reject_unsigned(self):
  with self.assertRaises(ValueError):p.verify(self.args)
 def test_reject_missing_key(self):
  self.sign()
  with patch.dict(os.environ,{"DOCWIZZ_APPROVAL_KEY":""}):
   with self.assertRaises(ValueError):p.verify(self.args)
 def test_exact_signature_and_tamper(self):
  self.sign()
  with patch.dict(os.environ,{"DOCWIZZ_APPROVAL_KEY":self.key}):
   p.verify(self.args)
   self.source.write_text(self.source.read_text()+"MODIFIED")
   with self.assertRaises(ValueError):p.verify(self.args)
 def test_reject_self_approval(self):
  self.sign(approver="alice")
  with patch.dict(os.environ,{"DOCWIZZ_APPROVAL_KEY":self.key}):
   with self.assertRaises(ValueError):p.verify(self.args)
 def test_reject_open_evidence(self):
  self.evidence.write_text(json.dumps({"document_control":{"document_id":"SWA-001","sha256":p.sha(self.control)},"required":{"total":1,"evidenced":0,"open":["scope"]}}))
  with self.assertRaises(ValueError):p.verify(self.args)
 def test_reject_missing_product_check(self):
  self.args.check_passed=False
  with self.assertRaises(ValueError):p.verify(self.args)
 def test_docx_layout_created(self):
  out=self.source.parent/"draft.docx"
  p.render(self.source.read_text(),out,"draft")
  from docx import Document
  self.assertIn("NICHT FREIGEGEBEN"," ".join(x.text for x in Document(out).paragraphs))
if __name__=="__main__":unittest.main()
