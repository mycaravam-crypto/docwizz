#!/usr/bin/env python3
"""Controlled DOCX/PDF publication. Approval is HMAC-bound to document inputs."""
import argparse, hashlib, hmac, json, os, pathlib, re, shutil, subprocess, sys, tempfile
from docx import Document
from docx.shared import Cm
from docx.oxml import OxmlElement
from docx.oxml.ns import qn

def sha(path): return hashlib.sha256(pathlib.Path(path).read_bytes()).hexdigest()
def canon(data): return json.dumps(data,sort_keys=True,separators=(",",":"),ensure_ascii=False).encode()
def verify(args):
    source, control, evidence = [pathlib.Path(x) for x in (args.source,args.control,args.evidence)]
    for path in (source,control,evidence):
        if not path.is_file(): raise ValueError("Missing input: "+str(path))
    text=source.read_text(encoding="utf-8")
    report=json.loads(evidence.read_text(encoding="utf-8"))
    ctl=report.get("document_control") or {}
    normalized=control.read_text(encoding="utf-8").replace("\r\n","\n").replace("\r","\n")
    if ctl.get("sha256") != hashlib.sha256(normalized.encode()).hexdigest(): raise ValueError("Document control changed")
    if not text.startswith("<!-- generated by docwizz product -->") or "## Deckblatt" not in text or "## Inhaltsverzeichnis" not in text:
        raise ValueError("Document not generated in controlled mode")
    if args.mode == "release":
        if not args.check_passed: raise ValueError("docwizz product check is mandatory")
        required=report.get("required") or {}
        if required.get("open") or required.get("total") != required.get("evidenced"):
            raise ValueError("Required sections lack evidence")
        if not args.attestation: raise ValueError("Signed approval attestation missing")
        key=os.environ.get("DOCWIZZ_APPROVAL_KEY","")
        if len(key)<32: raise ValueError("Protected approval key missing or too short")
        m=json.loads(pathlib.Path(args.attestation).read_text(encoding="utf-8"))
        if set(m)!={"payload","signature"}: raise ValueError("Invalid approval structure")
        p=m["payload"]
        fields={"schema","document_id","source_sha256","control_sha256","evidence_sha256","reviewer","approver"}
        if set(p)!=fields or p["schema"]!=1 or not all(isinstance(p[k],str) and p[k] for k in fields-{"schema"}):
            raise ValueError("Invalid approval payload")
        sig=hmac.new(key.encode(),canon(p),hashlib.sha256).hexdigest()
        if not isinstance(m["signature"],str) or not hmac.compare_digest(sig,m["signature"]):
            raise ValueError("Invalid approval signature")
        if p["reviewer"].casefold()==p["approver"].casefold(): raise ValueError("Two distinct reviewers required")
        if p["document_id"]!=ctl.get("document_id") or any(p[field]!=sha(path) for field,path in (
            ("source_sha256",source),("control_sha256",control),("evidence_sha256",evidence))):
            raise ValueError("Stale or mismatched approval")
    return text,report

def field(paragraph,instruction):
    run=paragraph.add_run()
    for kind in ("begin", "end"):
        ch=OxmlElement("w:fldChar");ch.set(qn("w:fldCharType"),kind)
        if kind=="begin":
            run._r.append(ch)
            inst=OxmlElement("w:instrText");inst.set(qn("xml:space"),"preserve");inst.text=instruction
            run._r.append(inst)
        else: run._r.append(ch)

def clean(text):
    text=re.sub(r"\[([^\]]+)\]\([^)]+\)",r"\1",text)
    return re.sub(r"(?<!\\)[*`]", "",text).replace("&amp;","&").replace("&lt;","<").replace("&gt;",">")

def render(text,dest,mode):
    doc=Document()
    section=doc.sections[0]
    section.page_width=Cm(21);section.page_height=Cm(29.7)
    section.left_margin=section.right_margin=Cm(2.4)
    section.top_margin=section.bottom_margin=Cm(2.2)
    title=next((line[2:] for line in text.splitlines() if line.startswith("# ")),"Dokument")
    doc.add_paragraph(clean(title),style="Title")
    doc.add_paragraph("FREIGABENACHWEIS VERIFIZIERT" if mode=="release" else "ENTWURF – NICHT FREIGEGEBEN")
    doc.add_page_break()
    doc.add_heading("Inhaltsverzeichnis",level=1)
    field(doc.add_paragraph(),'TOC \\o "1-3" \\h \\z \\u')
    doc.add_page_break()
    footer=section.footer.paragraphs[0]
    footer.add_run("DocWizz · "+mode.upper()+" · Seite ");field(footer,"PAGE")
    rows=[]
    def flush():
        nonlocal rows
        if not rows:return
        cols=len(rows[0]);tbl=doc.add_table(rows=0,cols=cols);tbl.style="Table Grid"
        for cells in rows:
            row=tbl.add_row()
            for i,value in enumerate(cells[:cols]):row.cells[i].text=clean(value)
        rows=[]
    for line in text.splitlines():
        if line.startswith("<!--") or line.startswith('<a id='):continue
        if line.startswith("|") and line.endswith("|"):
            cells=[c.strip() for c in re.split(r"(?<!\\)\|",line[1:-1])]
            if all(re.fullmatch(r":?-{3,}:?",x) for x in cells):continue
            if not rows or len(cells)==len(rows[0]):rows.append(cells);continue
        flush()
        if not line.strip() or line=="---" or line.startswith("# "):continue
        match=re.match(r"^(#{2,5})\s+(.*)",line)
        if match:doc.add_heading(clean(match.group(2)),level=min(len(match.group(1))-1,3))
        elif line.startswith(">"):doc.add_paragraph(clean(line[1:].strip()),style="Quote")
        elif re.match(r"^\s*[-*] ",line):doc.add_paragraph(clean(re.sub(r"^\s*[-*] ","",line)),style="List Bullet")
        else:doc.add_paragraph(clean(line))
    flush();doc.save(dest)

def main():
    ap=argparse.ArgumentParser()
    for key in ("mode","source","control","evidence","output"):
        ap.add_argument("--"+key,required=True,choices=["draft","release"] if key=="mode" else None)
    ap.add_argument("--attestation")
    ap.add_argument("--check-passed",action="store_true")
    args=ap.parse_args()
    try:
        text,report=verify(args)
        if not shutil.which("libreoffice"):raise ValueError("LibreOffice required for PDF")
        product=report.get("product","")
        if not re.fullmatch("[a-z0-9-]+",product):raise ValueError("Unsafe product ID")
        dest=pathlib.Path(args.output);dest.mkdir(parents=True,exist_ok=True)
        with tempfile.TemporaryDirectory() as tmp:
            docx=pathlib.Path(tmp)/(product+"-"+args.mode+".docx")
            render(text,docx,args.mode)
            subprocess.run(["libreoffice","-env:UserInstallation=file://"+tmp+"/lo","--headless",
                "--convert-to","pdf:writer_pdf_Export","--outdir",tmp,str(docx)],
                check=True,capture_output=True,timeout=90)
            pdf=docx.with_suffix(".pdf")
            if not pdf.is_file() or not pdf.read_bytes().startswith(b"%PDF"):raise ValueError("PDF invalid")
            for p in (docx,pdf):shutil.copyfile(p,dest/p.name)
    except (ValueError,OSError,subprocess.CalledProcessError,subprocess.TimeoutExpired,KeyError,json.JSONDecodeError) as e:
        print("Publication blocked: "+str(e),file=sys.stderr);return 1
    return 0
if __name__=="__main__":sys.exit(main())
